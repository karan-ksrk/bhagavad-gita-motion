"""Builds Android launcher icons and Play listing graphics (Milestone 15).

Usage: python tool/make_icons.py
Inputs:  media-production/generated-artwork/m15/icon_v001.png
         media-production/generated-artwork/m15/feature_graphic_v001.png
Outputs: android/app/src/main/res/mipmap-*/ (legacy + adaptive layers),
         android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml,
         media-production/store/play_icon_512.png,
         media-production/store/feature_graphic_1024x500.png
Needs Pillow.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "media-production/generated-artwork/m15"
RES = ROOT / "android/app/src/main/res"
STORE = ROOT / "media-production/store"

# Emblem height in the source is ~79% of the canvas. Adaptive icons show
# only the centre 66 of 108 dp (61%), so the art is shrunk to fit.
EMBLEM_SCALE = 0.68

DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}


def padded_icon(src: Image.Image) -> Image.Image:
    """Source art shrunk onto a matching blurred background, so the
    emblem sits inside the adaptive-icon safe zone with no visible seam."""
    size = src.width
    background = src.resize((size, size)).filter(ImageFilter.GaussianBlur(size // 6))
    inner = round(size * EMBLEM_SCALE)
    small = src.resize((inner, inner), Image.LANCZOS)

    # Soft round mask so the edge of the shrunk art fades into the
    # background.
    mask = Image.new("L", (inner, inner), 0)
    ImageDraw.Draw(mask).ellipse(
        (inner * 0.04, inner * 0.04, inner * 0.96, inner * 0.96), fill=255
    )
    mask = mask.filter(ImageFilter.GaussianBlur(inner * 0.05))

    out = background.copy()
    offset = (size - inner) // 2
    out.paste(small, (offset, offset), mask)
    return out


def monochrome(src: Image.Image) -> Image.Image:
    """White emblem silhouette on transparent, for Android 13 themed
    icons. Gold pixels (red channel high) become the shape."""
    r, g, b = src.convert("RGB").split()
    shape = r.point(lambda v: 255 if v > 140 else 0).filter(ImageFilter.MedianFilter(5))
    out = Image.new("RGBA", src.size, (255, 255, 255, 0))
    out.putalpha(shape)
    white = Image.new("RGBA", src.size, (255, 255, 255, 255))
    white.putalpha(shape)
    return white


def main() -> None:
    src = Image.open(SRC / "icon_v001.png").convert("RGB")
    size = min(src.size)
    src = src.crop((0, 0, size, size))

    full = padded_icon(src)
    mono_full = monochrome(src)
    # Same shrink as the colour layer, centred on a transparent canvas.
    inner = round(size * EMBLEM_SCALE)
    mono = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    mono.paste(mono_full.resize((inner, inner), Image.LANCZOS),
               ((size - inner) // 2, (size - inner) // 2))

    for name, scale in DENSITIES.items():
        folder = RES / f"mipmap-{name}"
        folder.mkdir(parents=True, exist_ok=True)
        legacy = round(48 * scale)
        layer = round(108 * scale)
        full.resize((legacy, legacy), Image.LANCZOS).save(folder / "ic_launcher.png")
        full.resize((layer, layer), Image.LANCZOS).save(
            folder / "ic_launcher_foreground.png"
        )
        mono.resize((layer, layer), Image.LANCZOS).save(
            folder / "ic_launcher_monochrome.png"
        )

    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/make_icons.py. -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n",
        encoding="utf-8",
    )
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<resources>\n"
        '    <color name="ic_launcher_background">#0B1426</color>\n'
        "</resources>\n",
        encoding="utf-8",
    )

    STORE.mkdir(parents=True, exist_ok=True)
    src.resize((512, 512), Image.LANCZOS).save(STORE / "play_icon_512.png")

    banner = Image.open(SRC / "feature_graphic_v001.png").convert("RGB")
    height = round(banner.width * 500 / 1024)
    top = (banner.height - height) // 2
    banner.crop((0, top, banner.width, top + height)).resize(
        (1024, 500), Image.LANCZOS
    ).save(STORE / "feature_graphic_1024x500.png")
    print("Icons and store graphics written.")


if __name__ == "__main__":
    main()
